package br.com.qaction.heranca;

public class Animal {
    private String nome;
    private int idade;

    // Getters && Setters:
    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public int getIdade() {
        return idade;
    }

    public void setIdade(int idade) {
        this.idade = idade;
    }
}
